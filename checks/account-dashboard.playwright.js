async (page) => {
  const context = await page.context().browser().newContext({ viewport: { width: 1440, height: 900 } });
  const test = await context.newPage();
  const base = new URL(page.url()).origin;
  const reports = [];
  const errors = [];
  test.on('pageerror', error => errors.push(error.message));
  const check = (condition, message) => { if (!condition) throw new Error(message); reports.push(`PASS: ${message}`); };
  const view = async key => {
    if ((await test.viewportSize()).width < 960) await test.locator('.member-menu').click();
    await test.locator(`[data-nav="${key}"]`).click();
    await test.waitForFunction(key => document.querySelector('[aria-current="page"]')?.dataset.nav === key, key);
  };
  try {
    await test.goto(`${base}/account.html`);
    await test.waitForURL('**/signin.html');
    check(true, 'Guest account access redirects to sign in');
    await test.getByRole('link', { name: 'Sign up', exact: true }).click();
    await test.locator('input[name=name]').fill('Duplicate Account');
    await test.locator('input[name=email]').fill('peter@gmail.com');
    await test.locator('input[name=password]').fill('123');
    await test.getByRole('button', { name: 'Create account', exact: true }).click();
    await test.getByText('Email sudah terdaftar. Silakan sign in.', { exact: true }).waitFor();
    check(true, 'Signup form submits and rejects an existing email');
    await test.getByRole('link', { name: 'Sign in', exact: true }).click();
    await test.locator('input[name=email]').fill('peter@gmail.com');
    await test.locator('input[name=password]').fill('salah');
    await test.getByRole('button', { name: 'Sign in', exact: true }).click();
    await test.getByText('Email atau password salah.', { exact: true }).waitFor();
    check(test.url().endsWith('/signin.html'), 'Incorrect password is rejected');
    check(await test.locator('.auth-error').evaluate(el => { const style = getComputedStyle(el); return parseFloat(style.fontSize) >= 16 && Number(style.fontWeight) >= 600 && style.borderTopStyle === 'solid'; }), 'Login error uses readable text and a visible alert container');
    await test.locator('input[name=password]').fill('123');
    await test.getByRole('button', { name: 'Sign in', exact: true }).click();
    await test.locator('.event-pass').waitFor();
    check((await test.locator('h1').innerText()).includes('Andreas Peterang'), 'Database credentials load Andreas Peterang');
    const cookies = await context.cookies();
    check(cookies.some(cookie => cookie.name === 'radius_session' && cookie.httpOnly), 'Server issues an HttpOnly session cookie');
    check((await context.request.get(`${base}/data/accounts.json`)).status() === 404, 'Private credentials JSON is not publicly served');
    check(await test.locator('.site-header,.account-header,.member-toolbar').count() === 0, 'Sign in opens independent dashboard without a top bar');
    await test.locator('[data-ticket]').first().click();
    check(await test.locator('dialog').evaluate(el => el.open), 'Ticket opens a native detail dialog');
    await test.evaluate(() => { window.print = () => { window.printRequested = true; }; });
    await test.locator('[data-print]').click();
    check(await test.evaluate(() => window.printRequested), 'Print ticket button calls browser print');
    await test.keyboard.press('Escape');
    check(await test.locator('dialog').evaluate(el => !el.open), 'Escape closes ticket dialog');
    check(await test.locator('[data-ticket]').first().evaluate(el => document.activeElement === el), 'Ticket dialog returns focus to its opener');
    await view('tickets');
    const all = await test.locator('.member-list-row').count();
    await test.locator('[data-filter="VALID"]').click();
    const upcoming = await test.locator('.member-list-row').count();
    await test.locator('[data-filter="ATTENDED"]').click();
    const attended = await test.locator('.member-list-row').count();
    check(all === upcoming + attended && upcoming > 0 && attended > 0, 'All, upcoming and attended filters show matching tickets');
    await view('orders');
    await test.locator('[data-order]').first().click();
    check((await test.locator('dialog').innerText()).includes('Total'), 'Order detail displays product and purchase total');
    await test.locator('[data-close-dialog]').click();
    await view('membership');
    await test.locator('[data-renewal]').click();
    await test.locator('[data-close-dialog]').last().click();
    check(await test.locator('dialog').evaluate(el => !el.open), 'Renewal confirmation can be cancelled');
    await test.locator('[data-renewal]').click();
    await test.locator('[data-confirm-renewal]').click();
    await test.locator('dialog').waitFor({ state: 'hidden' });
    check((await test.locator('.membership-settings').innerText()).includes('Nonaktif'), 'Renewal setting changes after confirmation');
    await view('overview');
    check((await test.locator('.membership-summary').innerText()).includes('Aktif sampai'), 'Overview reflects the changed renewal setting');
    await view('membership');
    await test.route('**/api/account/membership', route => route.fulfill({ status: 503, json: { error: 'Pengaturan gagal disimpan. Coba lagi.' } }));
    await test.locator('[data-renewal]').click();
    await test.locator('[data-confirm-renewal]').click();
    await test.getByText('Pengaturan gagal disimpan. Coba lagi.', { exact: true }).waitFor();
    check(await test.locator('dialog').evaluate(el => el.open), 'Failed membership save keeps confirmation open for retry');
    check((await context.request.get(`${base}/api/account`).then(r => r.json())).membershipCancelAtEnd === true, 'Failed membership save leaves database preference unchanged');
    await test.unroute('**/api/account/membership');
    await test.locator('[data-close-dialog]').last().click();
    await view('profile');
    await test.locator('input[name=name]').fill('   ');
    await test.locator('button[type=submit]').click();
    check(await test.locator('input[name=name]').evaluate(el => !el.validity.valid), 'Blank profile name is rejected');
    const name = 'Radius Member '.repeat(6).trim().slice(0, 80);
    await test.route('**/api/account/profile', route => route.fulfill({ status: 503, json: { error: 'Perubahan gagal disimpan. Coba lagi.' } }));
    await test.locator('input[name=name]').fill('Unsaved name');
    await test.locator('button[type=submit]').click();
    await test.getByText('Perubahan gagal disimpan. Coba lagi.', { exact: true }).waitFor();
    check(await test.locator('button[type=submit]').isEnabled(), 'Failed profile save gives feedback and permits retry');
    check((await context.request.get(`${base}/api/account`).then(r => r.json())).name === 'Andreas Peterang', 'Failed profile save does not change the database name');
    await test.unroute('**/api/account/profile');
    await test.locator('input[name=name]').fill(name);
    await test.locator('input[name=phone]').fill('08123456789');
    await test.locator('button[type=submit]').click();
    await test.getByText('Perubahan tersimpan.', { exact: true }).waitFor();
    await test.reload();
    await test.locator('[data-profile-form]').waitFor();
    check(await test.locator('input[name=name]').inputValue() === name, 'Profile changes persist after reload');
    const other = await page.context().browser().newContext();
    try {
      await other.request.post(`${base}/api/signin`, { data: { email: 'peter@gmail.com', password: '123' } });
      const saved = await other.request.get(`${base}/api/account`).then(r => r.json());
      check(saved.name === name && saved.phone === '08123456789', 'Profile is available in a separate browser context without localStorage');
      check(saved.membershipCancelAtEnd === true, 'Membership preference is available in a separate browser context');
      await other.request.post(`${base}/api/signout`, { data: {} });
    } finally { await other.close(); }
    for (const width of [320, 390, 768, 960, 1280, 1440]) {
      await test.setViewportSize({ width, height: 900 });
      for (const key of ['overview', 'tickets', 'orders', 'membership', 'profile']) {
        await view(key);
        check(await test.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${key} has no horizontal overflow at ${width}px`);
      }
    }
    await test.setViewportSize({ width: 390, height: 844 });
    await test.locator('.member-menu').click();
    check(await test.locator('.member-menu').getAttribute('aria-expanded') === 'true', 'Mobile account menu opens');
    await test.locator('.member-menu').click();
    check(await test.locator('.member-menu').getAttribute('aria-expanded') === 'false', 'Mobile account menu closes');
    await test.evaluate(() => document.documentElement.style.fontSize = '200%');
    check(await test.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Profile reflows at 200% text size on mobile');
    await test.evaluate(() => document.documentElement.style.fontSize = '');
    await test.locator('.member-menu').click();
    await test.locator('[data-signout]').click();
    await test.waitForURL('**/signin.html');
    check((await context.request.get(`${base}/api/session`)).status() === 401, 'Sign out revokes the server session');
    await test.evaluate(() => localStorage.setItem('radius_session', JSON.stringify({ email: 'peter@gmail.com', name: 'Forged user' })));
    await test.goto(`${base}/account.html`);
    await test.waitForURL('**/signin.html');
    check(true, 'A fabricated localStorage session cannot access the account');
    await test.locator('input[name=email]').fill('peter@gmail.com');
    await test.locator('input[name=password]').fill('123');
    await test.getByRole('button', { name: 'Sign in', exact: true }).click();
    await test.locator('.event-pass').waitFor();
    const response = await context.request.get(`${base}/api/account`);
    const fixture = await response.json();
    await test.route('**/api/account', route => route.fulfill({ status: 503, body: 'Unavailable' }));
    await test.goto(`${base}/account.html`);
    await test.locator('[data-retry]').waitFor();
    check((await test.locator('main').innerText()).includes('Akun belum bisa dimuat'), 'Failed account API load shows a retry action');
    await test.unroute('**/api/account');
    await test.locator('[data-retry]').click();
    await test.locator('.event-pass').waitFor();
    check(true, 'Retry reloads account data successfully');
    await test.route('**/api/account', route => route.fulfill({ json: { ...fixture, tickets: [], orderHistory: [], eventsAttended: 0, ticketsPurchased: 0, orders: 0 } }));
    await test.reload();
    await test.getByRole('heading', { name: 'Belum ada tiket berikutnya' }).waitFor();
    await view('tickets');
    check((await test.locator('main').innerText()).includes('Belum ada tiket di kategori ini'), 'Empty tickets shows a useful next action');
    await view('orders');
    check((await test.locator('main').innerText()).includes('Belum ada pesanan'), 'Empty orders shows a shop link');
    check(errors.length === 0, `No uncaught browser errors (${errors.length})`);
    return reports;
  } finally {
    await context.close();
  }
}
